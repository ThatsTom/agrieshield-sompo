create table if not exists public.agrishield_fazendas (
  id_fazenda bigint generated by default as identity primary key,
  nome_fazenda text not null check (char_length(btrim(nome_fazenda)) >= 2),
  numero_apolice text not null check (char_length(btrim(numero_apolice)) >= 3),
  apolices jsonb not null default '[]'::jsonb check (jsonb_typeof(apolices) = 'array'),
  arquivada boolean not null default false,
  cep text not null check (cep ~ '^[0-9]{5}-?[0-9]{3}$'),
  logradouro text not null default '',
  numero_km text not null default '',
  complemento text not null default '',
  bairro text not null default '',
  cidade text not null default '',
  uf text not null default '' check (uf = '' or uf ~ '^[A-Z]{2}$'),
  referencia_acesso text not null default '',
  tipo_operacao text not null default 'campo'
    check (tipo_operacao in ('campo', 'transporte')),
  proximidade_agua boolean not null default false,
  latitude double precision check (latitude is null or latitude between -90 and 90),
  longitude double precision check (longitude is null or longitude between -180 and 180),
  area_ha double precision check (area_ha is null or area_ha > 0),
  poligono jsonb check (poligono is null or jsonb_typeof(poligono) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint agrishield_fazendas_coordenadas_pares_check check (
    (latitude is null and longitude is null)
    or (latitude is not null and longitude is not null)
  )
);

create table if not exists public.agrishield_coordenadas_cep (
  cep text primary key check (cep ~ '^[0-9]{8}$'),
  logradouro text not null default '',
  bairro text not null default '',
  cidade text not null default '',
  uf text not null check (uf ~ '^[A-Z]{2}$'),
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  fonte text not null default 'base_estatica_demo',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

