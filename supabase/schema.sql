  area_ha_referencia double precision check (area_ha_referencia is null or area_ha_referencia > 0),
  raio_equivalente_m double precision check (raio_equivalente_m is null or raio_equivalente_m > 0),
  metodo_geometria text,
  raio_analise_m double precision not null check (raio_analise_m > 0),
  limiar_drenagem_km2 double precision not null check (limiar_drenagem_km2 >= 0),
  raio_busca_drenagem_m double precision not null check (raio_busca_drenagem_m > 0),
  declividade_media_graus double precision,
  posicao_topografica_relativa_m double precision,
  distancia_drenagem_m double precision check (distancia_drenagem_m is null or distancia_drenagem_m >= 0),
  area_drenagem_montante_km2 double precision check (area_drenagem_montante_km2 is null or area_drenagem_montante_km2 >= 0),
  schema_version text not null,
  algorithm_version text not null,
  fontes_json jsonb not null default '[]'::jsonb check (jsonb_typeof(fontes_json) = 'array'),
  qualidade_json jsonb not null default '{}'::jsonb check (jsonb_typeof(qualidade_json) = 'object'),
  erros_json jsonb not null default '[]'::jsonb check (jsonb_typeof(erros_json) = 'array'),
  cache_chave text,
  input_fingerprint text not null,
  calculado_em_utc timestamptz not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.agrishield_parametros_score (
  grupo text not null,
  indicador text not null,
  parametro text not null,
  valor_atual double precision not null check (
    valor_atual > '-Infinity'::double precision
    and valor_atual < 'Infinity'::double precision
  ),
  valor_padrao double precision not null check (
    valor_padrao > '-Infinity'::double precision
    and valor_padrao < 'Infinity'::double precision
  ),
  tipo text not null check (tipo in ('percentual', 'fator')),
  atualizado_em timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (grupo, indicador, parametro)
);

create table if not exists public.agrishield_clima_observacoes (
  id_fazenda bigint not null
    references public.agrishield_fazendas(id_fazenda) on delete cascade,
  data date not null,
  origem_dados text not null check (origem_dados in ('nasa_power', 'simulado')),
  ano smallint not null,
  mes smallint not null check (mes between 1 and 12),
  dia smallint not null check (dia between 1 and 31),
  temp_media_c double precision,
  temp_maxima_c double precision,
  temp_minima_c double precision,
  precipitacao_mm double precision check (precipitacao_mm is null or precipitacao_mm >= 0),
  umidade_relativa_pct double precision check (umidade_relativa_pct is null or umidade_relativa_pct between 0 and 100),
  radiacao_solar_mj double precision,
  vento_ms double precision check (vento_ms is null or vento_ms >= 0),
  dias_sem_chuva_consecutivos integer check (dias_sem_chuva_consecutivos is null or dias_sem_chuva_consecutivos >= 0),
  faixa_dias_sem_chuva text,
