  usuario_id uuid primary key
    references auth.users(id) on delete cascade,
  email text not null unique
    check (email = lower(btrim(email)) and position('@' in email) > 1),
  nome_completo text not null
    check (char_length(btrim(nome_completo)) between 2 and 120),
  funcao text not null default 'Consultor'
    check (char_length(btrim(funcao)) between 2 and 80),
  telefone text not null default ''
    check (char_length(telefone) <= 30),
  papel text not null default 'usuario'
    check (papel in ('usuario', 'administrador')),
