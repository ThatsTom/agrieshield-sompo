create table if not exists public.agrishield_fazendas (
  id_fazenda bigint generated by default as identity primary key,
  nome_fazenda text not null check (char_length(btrim(nome_fazenda)) >= 2),
  numero_apolice text not null check (char_length(btrim(numero_apolice)) >= 3),
  apolices jsonb not null default '[]'::jsonb check (jsonb_typeof(apolices) = 'array'),
  arquivada boolean not null default false,
  cep text not null check (cep ~ '^[0-9]{5}-?[0-9]{3}$'),
  logradouro text not null default '',
  numero_km text not null default '',
  complemento text not null default '',
  bairro text not null default '',
  cidade text not null default '',
  uf text not null default '' check (uf = '' or uf ~ '^[A-Z]{2}$'),
  referencia_acesso text not null default '',
  tipo_operacao text not null default 'campo'
    check (tipo_operacao in ('campo', 'transporte')),
  proximidade_agua boolean not null default false,
  latitude double precision check (latitude is null or latitude between -90 and 90),
  longitude double precision check (longitude is null or longitude between -180 and 180),
  area_ha double precision check (area_ha is null or area_ha > 0),
  poligono jsonb check (poligono is null or jsonb_typeof(poligono) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint agrishield_fazendas_coordenadas_pares_check check (
    (latitude is null and longitude is null)
    or (latitude is not null and longitude is not null)
  )
);

create table if not exists public.agrishield_maquinarios (
  id_maquinario bigint generated by default as identity primary key,
  id_fazenda bigint not null
    references public.agrishield_fazendas(id_fazenda) on delete cascade,
  tipo_equipamento text not null check (tipo_equipamento in (
    'TRATOR', 'COLHEITADEIRA', 'PULVERIZADOR_AUTOPROPELIDO',
    'PLANTADEIRA', 'IMPLEMENTO_ARRASTO', 'PLATAFORMA', 'UTILITARIO_APOIO'
  )),
  marca text not null check (marca in (
    'JOHN_DEERE', 'MASSEY_FERGUSON', 'NEW_HOLLAND', 'VALTRA',
    'CASE_IH', 'JACTO', 'STARA', 'OUTROS'
  )),
  marca_outro text check (
    marca_outro is null or char_length(btrim(marca_outro)) between 2 and 80
  ),
  modelo text not null check (char_length(btrim(modelo)) between 1 and 100),
  ano_fabricacao smallint not null check (ano_fabricacao between 1970 and 2100),
  chassi text check (chassi is null or char_length(btrim(chassi)) between 2 and 100),
  apelido text check (apelido is null or char_length(btrim(apelido)) between 1 and 80),
  horimetro_atual numeric(12,1) check (horimetro_atual is null or horimetro_atual >= 0),
  hodometro_atual numeric(14,1) check (hodometro_atual is null or hodometro_atual >= 0),
  media_horas_dia numeric(4,1) check (media_horas_dia is null or media_horas_dia between 0 and 24),
  possui_seguro boolean not null default false,
  seguradora text check (seguradora is null or seguradora in (
    'SOMPO', 'MAPFRE', 'PORTO_SEGURO', 'ALLIANZ', 'OUTRA'
  )),
  seguradora_outro text check (
    seguradora_outro is null or char_length(btrim(seguradora_outro)) between 2 and 80
  ),
  vencimento_apolice date,
  origem_cadastro text not null default 'manual'
    check (origem_cadastro in ('manual', 'csv', 'semente')),
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint agrishield_maquinarios_fazenda_chassi_key unique (id_fazenda, chassi),
  constraint agrishield_maquinarios_marca_outro_coerencia_check check (
    (marca = 'OUTROS' and marca_outro is not null)
    or (marca <> 'OUTROS' and marca_outro is null)
  ),
  constraint agrishield_maquinarios_horimetro_motor_check check (
    tipo_equipamento not in (
      'TRATOR', 'COLHEITADEIRA', 'PULVERIZADOR_AUTOPROPELIDO',
      'UTILITARIO_APOIO'
    ) or horimetro_atual is not null
  ),
  constraint agrishield_maquinarios_seguro_check check (
    (
      possui_seguro = true
      and seguradora is not null
      and vencimento_apolice is not null
      and (
        (seguradora = 'OUTRA' and seguradora_outro is not null)
        or (seguradora <> 'OUTRA' and seguradora_outro is null)
      )
    )
    or (
      possui_seguro = false
      and seguradora is null
      and seguradora_outro is null
      and vencimento_apolice is null
    )
  )
);

