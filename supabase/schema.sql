    check (char_length(motivo_rejeicao) <= 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint agrishield_login_admin_email_check check (
    papel <> 'administrador' or email = 'tomholanda300@gmail.com'
  ),
  constraint agrishield_login_admin_acesso_check check (
    email <> 'tomholanda300@gmail.com'
    or (papel = 'administrador' and status_acesso = 'aprovado')
  )
