begin;

create table public.agrishield_maquinarios (
  id_maquinario bigint generated by default as identity primary key,
  id_fazenda bigint not null
    references public.agrishield_fazendas(id_fazenda) on delete cascade,
  tipo_equipamento text not null check (tipo_equipamento in (
    'TRATOR',
    'COLHEITADEIRA',
    'PULVERIZADOR_AUTOPROPELIDO',
    'PLANTADEIRA',
    'IMPLEMENTO_ARRASTO',
    'PLATAFORMA',
    'UTILITARIO_APOIO'
  )),
  marca text not null check (marca in (
    'JOHN_DEERE',
    'MASSEY_FERGUSON',
    'NEW_HOLLAND',
    'VALTRA',
    'CASE_IH',
    'JACTO',
    'STARA',
    'OUTROS'
  )),
  marca_outro text check (
    marca_outro is null or char_length(btrim(marca_outro)) between 2 and 80
  ),
  modelo text not null check (char_length(btrim(modelo)) between 1 and 100),
  ano_fabricacao smallint not null check (ano_fabricacao between 1970 and 2100),
  chassi text check (
    chassi is null or char_length(btrim(chassi)) between 2 and 100
  ),
  apelido text check (
    apelido is null or char_length(btrim(apelido)) between 1 and 80
  ),
  horimetro_atual numeric(12,1) check (
    horimetro_atual is null or horimetro_atual >= 0
  ),
  hodometro_atual numeric(14,1) check (
    hodometro_atual is null or hodometro_atual >= 0
  ),
  media_horas_dia numeric(4,1) check (
    media_horas_dia is null or media_horas_dia between 0 and 24
  ),
  possui_seguro boolean not null default false,
  seguradora text check (seguradora is null or seguradora in (
    'SOMPO', 'MAPFRE', 'PORTO_SEGURO', 'ALLIANZ', 'OUTRA'
  )),
  seguradora_outro text check (
    seguradora_outro is null
    or char_length(btrim(seguradora_outro)) between 2 and 80
  ),
  vencimento_apolice date,
  origem_cadastro text not null default 'manual'
    check (origem_cadastro in ('manual', 'csv', 'semente')),
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint agrishield_maquinarios_fazenda_chassi_key unique (id_fazenda, chassi),
  constraint agrishield_maquinarios_marca_outro_coerencia_check check (
    (marca = 'OUTROS' and marca_outro is not null)
    or (marca <> 'OUTROS' and marca_outro is null)
  ),
  constraint agrishield_maquinarios_horimetro_motor_check check (
    tipo_equipamento not in (
      'TRATOR',
      'COLHEITADEIRA',
      'PULVERIZADOR_AUTOPROPELIDO',
      'UTILITARIO_APOIO'
    )
    or horimetro_atual is not null
  ),
  constraint agrishield_maquinarios_seguro_check check (
    (
      possui_seguro = true
      and seguradora is not null
      and vencimento_apolice is not null
      and (
        (seguradora = 'OUTRA' and seguradora_outro is not null)
        or (seguradora <> 'OUTRA' and seguradora_outro is null)
      )
    )
    or (
      possui_seguro = false
      and seguradora is null
      and seguradora_outro is null
      and vencimento_apolice is null
    )
  )
);

comment on table public.agrishield_maquinarios is
  'Inventario de maquinarios agricolas vinculados as fazendas do AgriShield.';
comment on column public.agrishield_maquinarios.origem_cadastro is
  'Origem do registro: cadastro individual, importacao CSV ou semente demonstrativa.';

create index agrishield_maquinarios_fazenda_ativo_created_idx
  on public.agrishield_maquinarios (id_fazenda, ativo, created_at desc);
create index agrishield_maquinarios_seguro_vencimento_idx
  on public.agrishield_maquinarios (id_fazenda, vencimento_apolice)
  where ativo = true and possui_seguro = true;

create trigger agrishield_maquinarios_updated_at
before update on public.agrishield_maquinarios
for each row execute function agrishield_private.set_updated_at();

alter table public.agrishield_maquinarios enable row level security;
revoke all on table public.agrishield_maquinarios from anon, authenticated;
grant select, insert, update, delete
  on table public.agrishield_maquinarios to service_role;
grant usage, select
  on sequence public.agrishield_maquinarios_id_maquinario_seq to service_role;

insert into public.agrishield_maquinarios (
  id_fazenda,
  tipo_equipamento,
  marca,
  modelo,
  ano_fabricacao,
  chassi,
  apelido,
  horimetro_atual,
  hodometro_atual,
  media_horas_dia,
  possui_seguro,
  seguradora,
  vencimento_apolice,
  origem_cadastro
)
select
  fazenda.id_fazenda,
  exemplo.tipo_equipamento,
  exemplo.marca,
  exemplo.modelo,
  exemplo.ano_fabricacao,
  exemplo.chassi,
  exemplo.apelido,
  exemplo.horimetro_atual,
  exemplo.hodometro_atual,
  exemplo.media_horas_dia,
  exemplo.possui_seguro,
  exemplo.seguradora,
  exemplo.vencimento_apolice,
  'semente'
from public.agrishield_fazendas as fazenda
cross join (
  values
    ('TRATOR', 'JOHN_DEERE', '7230J', 2022, 'DEMO-AC-JD7230J-01', 'Trator demonstrativo', 1250.5::numeric, null::numeric, 8.0::numeric, true, 'SOMPO', '2026-11-15'::date),
    ('COLHEITADEIRA', 'NEW_HOLLAND', 'CR 5.85', 2021, 'DEMO-AC-NHCR585-01', 'Colheitadeira demonstrativa', 1860.0::numeric, null::numeric, 7.5::numeric, true, 'SOMPO', '2027-07-20'::date),
    ('PULVERIZADOR_AUTOPROPELIDO', 'JACTO', 'Uniport 3030', 2023, 'DEMO-AC-JACTO3030-01', 'Pulverizador demonstrativo', 820.0::numeric, null::numeric, 6.0::numeric, false, null::text, null::date),
    ('PLANTADEIRA', 'STARA', 'Estrela 16 linhas', 2020, 'DEMO-AC-STARAESTRELA-01', 'Plantadeira demonstrativa', null::numeric, null::numeric, null::numeric, false, null::text, null::date)
) as exemplo (
  tipo_equipamento,
  marca,
  modelo,
  ano_fabricacao,
  chassi,
  apelido,
  horimetro_atual,
  hodometro_atual,
  media_horas_dia,
  possui_seguro,
  seguradora,
  vencimento_apolice
)
where lower(btrim(fazenda.nome_fazenda)) = lower('Embrapa Acre')
on conflict (id_fazenda, chassi) do nothing;

notify pgrst, 'reload schema';

commit;
